from abc import ABC, abstractmethod
from typing import Dict, Any, List, Optional
from backend.app.models.models import SearchModeType
from backend.app.core.config import settings
from backend.app.services.embedding_service import embedding_service
from backend.app.services.chroma_service import chroma_service

class SearchFilterStrategy(ABC):
    @abstractmethod
    def build_filter(self, user_id: int) -> Dict[str, Any]:
        """Constructs ChromaDB scalar metadata filter."""
        pass

class PrivateSearchStrategy(SearchFilterStrategy):
    def build_filter(self, user_id: int) -> Dict[str, Any]:
        return {
            "$and": [
                {"owner_id": {"$eq": user_id}},
                {"visibility": {"$eq": "PERSONAL"}}
            ]
        }

class PublicSearchStrategy(SearchFilterStrategy):
    def build_filter(self, user_id: int) -> Dict[str, Any]:
        return {
            "visibility": {"$eq": "PUBLIC"}
        }

class CombinedSearchStrategy(SearchFilterStrategy):
    def build_filter(self, user_id: int) -> Dict[str, Any]:
        return {
            "$or": [
                {
                    "$and": [
                        {"owner_id": {"$eq": user_id}},
                        {"visibility": {"$eq": "PERSONAL"}}
                    ]
                },
                {"visibility": {"$eq": "PUBLIC"}}
            ]
        }

class RAGQueryEngineService:
    def __init__(self):
        self._strategies = {
            SearchModeType.PRIVATE: PrivateSearchStrategy(),
            SearchModeType.PUBLIC: PublicSearchStrategy(),
            SearchModeType.COMBINED: CombinedSearchStrategy(),
        }

    def get_filter_for_mode(self, mode: SearchModeType, user_id: int) -> Dict[str, Any]:
        strategy = self._strategies.get(mode, self._strategies[SearchModeType.PRIVATE])
        return strategy.build_filter(user_id)

    def retrieve_context(
        self,
        query: str,
        mode: SearchModeType,
        user_id: int,
        top_k: int = 5
    ) -> List[Dict[str, Any]]:
        query_vector = embedding_service.generate_embedding(query)
        where_filter = self.get_filter_for_mode(mode, user_id)
        chunks = chroma_service.query_vectors(
            query_vector=query_vector,
            where_filter=where_filter,
            top_k=top_k
        )
        return chunks

    def synthesize_answer(self, query: str, chunks: List[Dict[str, Any]]) -> str:
        fallback_no_info = "No relevant information found in the selected search scope."
        if not chunks:
            return fallback_no_info

        context_passages = []
        for i, chunk in enumerate(chunks, 1):
            meta = chunk.get("metadata", {})
            filename = meta.get("filename", "Unknown Document")
            text = chunk.get("chunk_text", "").strip()
            context_passages.append(f"Passage [{i}] (File: {filename}):\n{text}")

        context_text = "\n\n".join(context_passages)

        system_prompt = (
            "You are an AI Document Management and Question Answering Assistant. "
            "Answer the user's question STRICTLY and ACCURATELY based ONLY on the provided context passages below. "
            "If the provided context does not contain enough information to answer the question, reply with EXACTLY: "
            f"'{fallback_no_info}'\n"
            "Include inline references or citations to the file names when mentioning facts from the context."
        )

        user_prompt = f"Context:\n{context_text}\n\nQuestion: {query}\n\nAnswer:"

        if settings.OPENAI_API_KEY:
            try:
                from openai import OpenAI
                client = OpenAI(api_key=settings.OPENAI_API_KEY)
                response = client.chat.completions.create(
                    model=settings.LLM_MODEL,
                    messages=[
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": user_prompt}
                    ],
                    temperature=0.0
                )
                answer = response.choices[0].message.content
                if answer and answer.strip():
                    print(f"\n=======================================================\n[DEBUG OUTPUT SOURCE] >>> Output generated by OPENAI API ({settings.LLM_MODEL}) <<<\n=======================================================\n")
                    return answer.strip()
            except Exception as e:
                print(f"[RAGQueryEngineService] OpenAI Chat Completion error: {e}. Falling back to rule-based synthesis.")

        # Grounded fallback synthesis when OpenAI key is not provided or fails
        print(f"\n=======================================================\n[DEBUG OUTPUT SOURCE] >>> Output generated by LOCAL RULE-BASED EXTRACTOR (Fallback) <<<\n=======================================================\n")
        # Extract matching sentences from the retrieved chunks
        relevant_sentences = []
        q_words = set(query.lower().split())
        for chunk in chunks:
            text = chunk.get("chunk_text", "")
            sentences = text.replace("\n", " ").split(". ")
            for s in sentences:
                s_clean = s.strip()
                if s_clean and any(w in s_clean.lower() for w in q_words if len(w) > 3):
                    if s_clean not in relevant_sentences:
                        relevant_sentences.append(s_clean)

        if relevant_sentences:
            best_extract = ". ".join(relevant_sentences[:4])
            if not best_extract.endswith("."):
                best_extract += "."
            filenames = {c.get("metadata", {}).get("filename", "Document") for c in chunks}
            return f"Based on the retrieved context from [{', '.join(filenames)}]:\n\n{best_extract}"

        # If chunks exist, return the most relevant passage
        first_chunk = chunks[0]
        meta = first_chunk.get("metadata", {})
        fname = meta.get("filename", "Document")
        snippet = first_chunk.get("chunk_text", "")[:350].strip()
        return f"According to [{fname}]: {snippet}..."

rag_query_engine = RAGQueryEngineService()
